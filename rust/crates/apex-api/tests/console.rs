#[tokio::test]
async fn audit_page_golden_structure_matches_the_engine_report() {
    let temp = TempDir::new("console-audit-golden");
    write_standard_fixture(temp.path());
    let app = router(file_state(temp.path(), pub1_keys()));
    let response = send(&app, get("/console/audit?platform=admob")).await;
    assert_eq!(response.status, 200);
    assert!(response.content_type().starts_with(HTML));

    let report = report_for(&minimal_snapshot(&["u1"]));
    for header in [
        "<th>Rule</th>",
        "<th>Severity</th>",
        "<th>Platform</th>",
        "<th>Subject</th>",
        "<th>Message</th>",
        "<th>Recovery (micros)</th>",
    ] {
        assert!(response.body.contains(header), "missing {header}");
    }
    assert!(response.body.contains(&format!(
        "Total estimated monthly recovery: <strong>{}</strong> micros",
        report.total_estimated_monthly_recovery
    )));
    assert!(response
        .body
        .contains(&format!("Findings: {} (critical: ", report.findings.len())));
    assert!(response
        .body
        .contains(&format!("<code>{}</code>", report.snapshot_digest)));
    for finding in &report.findings {
        assert!(
            response.body.contains(&finding.subject),
            "missing subject {}",
            finding.subject
        );
        assert!(
            response.body.contains(finding.rule.as_str()),
            "missing rule {}",
            finding.rule.as_str()
        );
        assert!(response.body.contains(finding.severity.as_str()));
    }
    assert!(response.body.contains("Generated by: apex-audit v0.1.0"));
}

