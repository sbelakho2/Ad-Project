#!/usr/bin/env node
// sync-floors.mjs — keeps tools/coverage/floors.txt (shell-readable mirror, used by
// pipeline commands inside images without node/python) in lockstep with the JSON
// source of truth (tools/coverage/coverage-floor.json).
//   --write : regenerate floors.txt from coverage-floor.json
//   --check : fail if they differ (also run by dogfood-audit via dogfood-gates floors-sync)
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from './coverage-lib.mjs';

const write = process.argv.includes('--write');
const floorJson = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'tools/coverage/coverage-floor.json'), 'utf8'));

const lines = [
  '# GENERATED by tools/coverage/sync-floors.mjs — DO NOT EDIT.',
  '# Source of truth: tools/coverage/coverage-floor.json (ratchet-only; see design doc 0.4).',
  '# Format: <domain> <minimum-percent> (all four metrics, where the tool supports them).',
];
for (const [domain, floor] of Object.entries(floorJson.domains)) {
  lines.push(`${domain} ${floor}`);
}
const content = `${lines.join('\n')}\n`;
const target = path.join(REPO_ROOT, 'tools/coverage/floors.txt');

if (write) {
  fs.writeFileSync(target, content);
  console.log(`floors.txt written (${Object.keys(floorJson.domains).length} domains)`);
} else {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error('floors.txt out of sync with coverage-floor.json — run: node tools/coverage/sync-floors.mjs --write');
    process.exit(1);
  }
  console.log('floors.txt in sync');
}
